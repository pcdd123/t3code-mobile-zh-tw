// summarizeToolGroup joins up to four labels, lowercasing all but the first.
function joins(gt: Translate): ReadonlyArray<Sentence> {
  return [
    (v) => gt("{action} and {nextAction}", v),
    (v) => gt("{first}, {second}, and {third}", v),
    (v) => gt("{first}, {second}, {third}, and {fourth}", v),
  ];
}

const NUMBER_PLACEHOLDERS = new Set([
  "count",
  "messages",
  "threads",
  "attachments",
  "failed",
  "done",
  "total",
]);
const PLACEHOLDER_PATTERNS: Readonly<Record<string, string>> = {
  pullRequest: String.raw`.+ #\d+`,
};

interface CompiledSentence {
  readonly index: number;
  readonly pattern: RegExp;
  readonly names: ReadonlyArray<string>;
}

const sourceOnly = ((message: string) => message) as unknown as Translate;

function firstWord(text: string): string {
  const space = text.indexOf(" ");
  return space === -1 ? text : text.slice(0, space);
}

function compile(source: string, index: number): CompiledSentence {
  const names: string[] = [];
  const pattern = source
    .split(/\{(\w+)\}/)
    .map((part, position) => {
      if (position % 2 === 0) return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      names.push(part);
      return `(${PLACEHOLDER_PATTERNS[part] ?? (NUMBER_PLACEHOLDERS.has(part) ? String.raw`\d+` : ".+")})`;
    })
    .join("");
  return { index, pattern: new RegExp(`^${pattern}$`), names };
}

// Sentences grouped by their first word; ones that start with a placeholder are under "".
let buckets: ReadonlyMap<string, ReadonlyArray<CompiledSentence>> | null = null;

function sentenceBuckets() {
  if (buckets !== null) return buckets;
  const grouped = new Map<string, CompiledSentence[]>();
  sentences(sourceOnly).forEach((sentence, index) => {
    const source = sentence({});
    const key = source.startsWith("{") ? "" : firstWord(source);
    const bucket = grouped.get(key);
    const compiled = compile(source, index);
    if (bucket) bucket.push(compiled);
    else grouped.set(key, [compiled]);
  });
  buckets = grouped;
  return grouped;
}

interface SentenceMatch {
  readonly index: number;
  readonly values: Values;
}

// Timelines localize every row label on each render, and labels repeat across renders.
const matchCache = new Map<string, SentenceMatch | null>();
const MATCH_CACHE_LIMIT = 5_000;

function findSentence(label: string): SentenceMatch | null {
  const all = sentenceBuckets();
  for (const candidates of [all.get(firstWord(label)), all.get("")]) {
    for (const candidate of candidates ?? []) {
      const result = candidate.pattern.exec(label);
      if (result === null) continue;
      const values: Record<string, string> = {};
      candidate.names.forEach((name, position) => {
        values[name] = result[position + 1] ?? "";
      });
      return { index: candidate.index, values };
    }
  }
  return null;
}

function matchSentence(label: string): SentenceMatch | null {
  const cached = matchCache.get(label);
  if (cached !== undefined) return cached;
  const match = findSentence(label);
  if (matchCache.size >= MATCH_CACHE_LIMIT) matchCache.clear();
  matchCache.set(label, match);
  return match;
}

const sentenceLists = new WeakMap<Translate, ReadonlyArray<Sentence>>();

function sentencesFor(gt: Translate): ReadonlyArray<Sentence> {
  let list = sentenceLists.get(gt);
  if (list === undefined) {
    list = sentences(gt);
    sentenceLists.set(gt, list);
  }
  return list;
}

// Source names in "Used … integrations" are joined in English by summarizeToolGroup.
function localizeNames(names: string, gt: Translate): string {
  const pair = /^([^,]+) and ([^,]+)$/.exec(names);
  return pair ? gt("{first} and {second}", { first: pair[1] ?? "", second: pair[2] ?? "" }) : names;
}

function render(match: SentenceMatch, gt: Translate): string {
  const { names } = match.values;
  const values =
    names === undefined ? match.values : { ...match.values, names: localizeNames(names, gt) };
  return sentencesFor(gt)[match.index]?.(values) ?? "";
}

const SEPARATOR = /(, and | and |, )/;
const MAX_PARTS = 4;

/** Splits a joined summary into known labels; null unless at least two parts match. */
function matchParts(label: string): SentenceMatch[] | null {
  const pieces = label.split(SEPARATOR);
  const tokenCount = (pieces.length + 1) / 2;
  if (tokenCount < 2) return null;
  const partsFrom = (start: number, depth: number): SentenceMatch[] | null => {
    for (let end = start + 1; end <= tokenCount; end += 1) {
      if (start === 0 && end === tokenCount) break;
      const text = pieces.slice(start * 2, end * 2 - 1).join("");
      const match = matchSentence(
        start === 0 ? text : text.charAt(0).toUpperCase() + text.slice(1),
      );
      if (match === null) continue;
      if (end === tokenCount) return [match];
      if (depth + 1 >= MAX_PARTS) continue;
      const rest = partsFrom(end, depth + 1);
      if (rest !== null) return [match, ...rest];
    }
    return null;
  };
  return partsFrom(0, 0);
}

function joinParts(parts: ReadonlyArray<string>, gt: Translate): string {
  const [first = "", second = "", third = "", fourth = ""] = parts;
  const list = joins(gt);
  switch (parts.length) {
    case 2:
      return list[0]!({ action: first, nextAction: second });
    case 3:
      return list[1]!({ first, second, third });
    default:
      return list[2]!({ first, second, third, fourth });
  }
}

/** Translates a work log tool label or tool group summary; null when the label is unknown. */
export function localizeToolActivityLabel(label: string, gt: Translate): string | null {
  const parts = SEPARATOR.test(label) ? matchParts(label) : null;
  if (parts !== null) {
    const rendered = parts.map((part, index) => {
      const text = render(part, gt);
      return index === 0 ? text : text.charAt(0).toLowerCase() + text.slice(1);
    });
    return joinParts(rendered, gt);
  }
  const match = matchSentence(label);
  return match === null ? null : render(match, gt);
}
